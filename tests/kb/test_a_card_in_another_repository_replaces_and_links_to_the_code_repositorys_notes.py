def _pairs(vault):
    from src.vault.reader import vault_note_files

    return [catalog.load(vault, f) for f in vault_note_files(vault)]


def test_the_graph_draws_a_note_of_another_repository_as_an_external_node(world):
    infos = {CODE: [i for i, _ in _pairs(world.vault(CODE))]}
    g = links.graph(_pairs(world.vault(KB)), repo=KB, code_repo=CODE, foreign=lambda r: infos.get(r))
    ext = {n["path"]: n for n in g["nodes"] if n.get("external")}
    assert set(ext) == {f"{CODE}:processes/{RESERVE}.md", f"{CODE}:processes/{LEDGER}.md"}
    node = ext[f"{CODE}:processes/{LEDGER}.md"]
    assert node["repo"] == CODE and node["note_path"] == f"processes/{LEDGER}.md" and node["type"] == "process"
    assert {"source": "kb/reserve.md", "target": f"{CODE}:processes/{LEDGER}.md", "kind": "related",
            "repo": CODE} in g["edges"]
    assert g["dangling"] == {}
    # not readable: the link dangles and nothing of the other repository is drawn
    g2 = links.graph(_pairs(world.vault(KB)), repo=KB, code_repo=CODE, foreign=lambda r: None)
    assert not [n for n in g2["nodes"] if n.get("external")] and "kb/reserve.md" in g2["dangling"]


def test_the_code_repositorys_note_has_back_links_from_cards_bound_to_it(world):
    own = _pairs(world.vault(CODE))
    bound = {KB: _pairs(world.vault(KB))}
    nb = links.neighbours(f"processes/{LEDGER}.md", own, repo=CODE, bound=bound)
    back = {(b["repo"], b["path"], b["kind"]) for b in nb["back"] if b.get("repo")}
    assert back == {(KB, "kb/reserve.md", "related"), (KB, "kb/explicit.md", "replaces")}
    assert links.neighbours(f"processes/{LEDGER}.md", own, repo=CODE)["back"] == []


def test_a_module_notes_callers_are_a_called_by_link(world):
    from src.vault.writer import NoteMetadata, VaultWriter

    w = VaultWriter(workspace_id=WS)
    w.write(repo=CODE, relative_path="modules/a.md", content="# A\n",
            metadata=NoteMetadata(type="module", repo=CODE, computed={"cross_refs": [], "callers_modules": ["modules/b"]}))
    w.write(repo=CODE, relative_path="modules/b.md", content="# B\n",
            metadata=NoteMetadata(type="module", repo=CODE))
    g = links.graph(_pairs(world.vault(CODE)))
    assert {"source": "modules/a.md", "target": "modules/b.md", "kind": "called-by"} in g["edges"]


def test_a_body_link_to_a_note_the_front_matter_already_names_is_one_edge(world):
    """The card names the note in ``related`` and links it again in its text:
    the graph drew two edges for one relation (the declared one wins)."""
    store.import_cards(KB, [
        ("pair/a.md", card(id="pair-a", extra="related: [pair/b]",
                           body="# A\n\nДив. [B](b.md) і ще раз [[pair/b]].\n")),
        ("pair/b.md", card(id="pair-b", body="# B\n\nПро B.\n")),
    ], workspace_id=WS, replace=False)
    g = links.graph(_pairs(world.vault(KB)), repo=KB)
    edges = [e for e in g["edges"] if e["source"] == "kb/pair/a.md"]
    assert edges == [{"source": "kb/pair/a.md", "target": "kb/pair/b.md", "kind": "related"}]
