"""The audit as one document.

Everything the dependencies page shows lives across four collapsible panels in
a browser session. These pin the properties that make the exported version
usable by someone who was not there when it ran: it says where it came from,
and it says what nobody checked BEFORE it says what was found.
"""

from __future__ import annotations

from types import SimpleNamespace

from src.deps.document import PRODUCT, build_markdown


def _finding(**kw):
    base = dict(
        repo_slug="acme/api", ecosystem="PyPI", package="django",
        current_version="4.2.25", latest_version="6.1", outdated="major",
        is_dev=False, vulns=[], severity="none", recommendation="ok",
    )
    base.update(kw)
    return SimpleNamespace(**base)


def _run(**summary):
    base = {
        "repos_scanned": 2, "repos_total": 2, "packages": 10,
        "unique_packages": 8, "transitive": 3, "outdated": 5, "vulnerable": 2,
        "by_severity": {"critical": 1, "high": 1},
    }
    base.update(summary)
    return SimpleNamespace(id="run-1", summary=base)


def test_the_document_says_who_produced_it():
    """A report pasted into a ticket without attribution reads as somebody's
    hand-written opinion — which is exactly how it gets ignored or over-trusted."""
    md = build_markdown(_run(), [_finding()], generated_at="2026-08-14")
    assert md.startswith(f"# {PRODUCT} — Dependency Audit")
    assert f"Generated by {PRODUCT} on 2026-08-14" in md
    assert "run `run-1`" in md


def test_coverage_comes_before_findings():
    """An unchecked ecosystem reports zero vulnerabilities exactly like a clean
    one. A reader who meets the findings first has already formed an
    impression by the time the caveat arrives."""
    md = build_markdown(
        _run(not_checked=[{"repo": "acme/api", "ecosystem": "PyPI",
                           "tool": "pip-audit", "reason": "resolution failed"}]),
        [_finding()], generated_at="2026-08-14")
    assert md.index("## Coverage & sources") < md.index("## Findings by repository")


def test_what_nobody_checked_is_named_not_counted():
    """"5 not checked" is not actionable. Which repo, which ecosystem, and why."""
    md = build_markdown(
        _run(not_checked=[{"repo": "acme/web", "ecosystem": "npm",
                           "tool": "npm-audit", "subproject": "frontend",
                           "reason": "no lock file"}]),
        [], generated_at="2026-08-14")
    assert "Not fully checked (1)" in md
    assert "acme/web/frontend" in md
    assert "no lock file" in md
    assert "npm-audit" in md
    # The caveat itself has to survive into the document, not just the list.
    assert "unknown" in md and "safe" in md


def test_a_partial_scan_is_not_described_as_unchecked():
    """pip-audit's pinned-only fallback DOES see the direct dependencies.
    Calling that "not checked" understates it as badly as calling it
    "checked" overstates it."""
    md = build_markdown(
        _run(not_checked=[
            {"repo": "acme/api", "ecosystem": "PyPI", "tool": "pip-audit",
             "status": "partial",
             "reason": "dependency resolution failed — audited 27 pinned "
                       "requirements directly, without the transitive tree"},
        ]),
        [], generated_at="2026-08-14")
    assert "saw the direct dependencies but not the transitive tree" in md
    assert "27 pinned requirements" in md
    assert "Treat a zero here as *unknown*" in md
    # There is no second category of gap in this run — describing one invents
    # a remainder the reader will go looking for.
    assert "the rest" not in md


def test_a_mixed_coverage_gap_describes_both_kinds():
    md = build_markdown(
        _run(not_checked=[
            {"repo": "acme/api", "ecosystem": "PyPI", "tool": "pip-audit",
             "status": "partial", "reason": "resolution failed"},
            {"repo": "acme/web", "ecosystem": "npm", "tool": "npm-audit",
             "status": "not_checked", "reason": "no lock file"},
        ]),
        [], generated_at="2026-08-14")
    assert "Not fully checked (2)" in md
    assert "1 saw the direct dependencies" in md
    assert "the rest fell back to lock files" in md


def test_a_clean_coverage_report_says_so_explicitly():
    """Silence where the caveat would be reads as a missing section."""
    md = build_markdown(_run(sources={"osv": 3}), [], generated_at="2026-08-14")
    assert "Every detected ecosystem was audited by its native tool." in md


def test_vulnerable_packages_carry_severity_and_where_the_fix_is():
    md = build_markdown(
        _run(),
        [_finding(severity="critical", package="python-jose",
                  current_version="3.3.0", latest_version="3.5.0",
                  vulns=[{"cve": "CVE-2024-33663", "fixed_in": "3.4.0"}])],
        generated_at="2026-08-14")
    assert "**CRITICAL**" in md
    assert "`python-jose` 3.3.0 → 3.5.0" in md
    assert "CVE-2024-33663 (fixed in 3.4.0)" in md


def test_a_vulnerability_with_no_fix_says_so():
    """"no fix yet" changes the action from "upgrade" to "mitigate or accept" —
    printing the CVE alone hides that."""
    md = build_markdown(
        _run(),
        [_finding(severity="high", package="ecdsa",
                  vulns=[{"cve": "CVE-2024-23342"}])],
        generated_at="2026-08-14")
    assert "CVE-2024-23342 (no fix yet)" in md


def test_findings_are_grouped_by_repository():
    md = build_markdown(
        _run(),
        [_finding(repo_slug="acme/api"), _finding(repo_slug="acme/web")],
        generated_at="2026-08-14")
    assert "### acme/api" in md
    assert "### acme/web" in md


def test_the_ai_report_is_embedded_and_attributed():
    md = build_markdown(
        _run(ai_report="## 1. Headline\n\nUpdate django first.",
             ai_report_engine="claude_code"),
        [], generated_at="2026-08-14")
    assert "## Executive summary" in md
    assert "Update django first." in md
    assert f"Written by {PRODUCT} using claude_code" in md
    # The distinction that keeps the document trustworthy.
    assert "facts are measured" in md


def test_a_failed_report_is_stated_rather_than_omitted():
    """A missing section is indistinguishable from a report nobody asked for."""
    md = build_markdown(
        _run(ai_report_error="no Claude account connected"), [],
        generated_at="2026-08-14")
    assert "Not generated: no Claude account connected" in md


def test_a_truncated_finding_list_says_how_many_were_dropped():
    """Silent truncation reads as 'this is everything'."""
    from src.deps.document import MAX_CLEAN_ROWS

    rows = [_finding(package=f"pkg{i}", severity="none", outdated="minor")
            for i in range(MAX_CLEAN_ROWS + 25)]
    md = build_markdown(_run(), rows, generated_at="2026-08-14")
    assert "25 further outdated packages" in md


def test_vulnerable_rows_are_never_dropped_by_the_cap():
    """The cap exists to keep the document readable, not to hide risk."""
    from src.deps.document import MAX_CLEAN_ROWS

    rows = [_finding(package=f"clean{i}", outdated="minor")
            for i in range(MAX_CLEAN_ROWS + 50)]
    rows += [_finding(package="bad", severity="critical",
                      vulns=[{"cve": "CVE-1", "fixed_in": "2.0"}])]
    md = build_markdown(_run(), rows, generated_at="2026-08-14")
    assert "`bad`" in md and "CVE-1" in md


def test_the_document_round_trips_into_an_openable_docx():
    """The .docx path is hand-written XML, so 'it produced bytes' is not
    evidence — Word has to be able to open it."""
    import io
    import zipfile

    from src.docs.export import to_docx_document

    md = build_markdown(
        _run(ai_report="# Head\n\n- bullet with <angle> & ampersand"),
        [_finding(severity="critical", vulns=[{"cve": "CVE-1"}])],
        generated_at="2026-08-14")
    blob = to_docx_document(md)
    assert blob[:2] == b"PK"
    z = zipfile.ZipFile(io.BytesIO(blob))
    assert z.testzip() is None
    assert set(z.namelist()) == {
        "[Content_Types].xml", "_rels/.rels", "word/_rels/document.xml.rels",
        "word/styles.xml", "word/document.xml",
    }
    doc = z.read("word/document.xml").decode("utf-8")
    assert PRODUCT in doc
    # XML escaping — an unescaped & or < makes the file unopenable.
    assert "&amp;" in doc and "&lt;angle&gt;" in doc
