"""The audit as a document someone can send to a colleague.

The dependencies page already holds everything a reader needs — the overview
counts, which auditor produced what, what nobody checked, the AI summary and
327 individual findings — but it holds them across four collapsible panels in a
browser session. A person who has to hand the result to a security reviewer, a
client or a ticket has no way to take it with them.

This assembles one markdown document from the run. Markdown because the AI
report is already markdown and the findings are a table of facts, so nothing is
translated; `src.docs.export` turns the same string into a .docx, and the
browser prints it to PDF with the typography it shows on screen.

Order is deliberate: what nobody checked comes BEFORE the findings, because an
unchecked ecosystem reports zero vulnerabilities exactly like a clean one, and
a reader who meets the findings first has already formed an impression by the
time the caveat arrives.
"""

from __future__ import annotations

from typing import Any

#: Every exported artifact says where it came from. A report that lands in a
#: ticket without attribution gets treated as somebody's hand-written opinion.
PRODUCT = "Celmis"

_SEV_RANK = {"critical": 0, "high": 1, "medium": 2, "low": 3, "none": 4}
_SEV_LABEL = {"critical": "CRITICAL", "high": "HIGH", "medium": "MEDIUM",
              "low": "LOW", "none": ""}

#: Past this the document stops being readable and becomes a data dump. The
#: count of what was dropped is printed rather than silently truncated.
MAX_CLEAN_ROWS = 400


def _fmt_int(value: Any) -> str:
    return f"{value:,}".replace(",", " ") if isinstance(value, int) else str(value or 0)


def _severity_line(by_severity: dict[str, int]) -> str:
    parts = [f"{by_severity.get(k, 0)} {k}"
             for k in ("critical", "high", "medium", "low")
             if by_severity.get(k)]
    return " · ".join(parts) if parts else "none"


def _vuln_bits(vulns: list[dict], limit: int = 4) -> str:
    """CVE ids with where the fix is, which is the only part that is actionable."""
    out = []
    for v in (vulns or [])[:limit]:
        ident = v.get("cve") or v.get("id") or "?"
        fixed = v.get("fixed_in")
        out.append(f"{ident} ({'fixed in ' + fixed if fixed else 'no fix yet'})")
    extra = len(vulns or []) - limit
    if extra > 0:
        out.append(f"+{extra} more")
    return "; ".join(out)


def build_markdown(
    run: Any,
    findings: list[Any],
    *,
    generated_at: str,
    scope: str = "",
) -> str:
    """One document: header, overview, coverage, AI report, findings by repo."""
    summary: dict[str, Any] = dict(getattr(run, "summary", None) or {})
    lines: list[str] = [
        f"# {PRODUCT} — Dependency Audit",
        "",
        f"_Generated by {PRODUCT} on {generated_at} · run `{getattr(run, 'id', '')}`_",
    ]
    if scope:
        lines.append(f"_Scope: {scope}_")
    lines.append("")

    # ─── Overview ────────────────────────────────────────────────────
    by_sev = summary.get("by_severity") or {}
    lines += [
        "## Overview",
        "",
        f"- **Repositories scanned:** {_fmt_int(summary.get('repos_scanned'))}"
        f" of {_fmt_int(summary.get('repos_total'))}",
        f"- **Packages:** {_fmt_int(summary.get('packages'))}"
        f" ({_fmt_int(summary.get('unique_packages'))} unique,"
        f" {_fmt_int(summary.get('transitive'))} transitive)",
        f"- **Outdated:** {_fmt_int(summary.get('outdated'))}",
        f"- **Vulnerable:** {_fmt_int(summary.get('vulnerable'))}"
        f" — {_severity_line(by_sev)}",
    ]
    groups = summary.get("groups") or {}
    if groups:
        lines.append(
            f"- **Recommended:** {_fmt_int(groups.get('update_now'))} update now, "
            f"{_fmt_int(groups.get('update_safe'))} safe to batch, "
            f"{_fmt_int(groups.get('plan_major'))} major upgrades to plan"
        )
    skipped = summary.get("repos_skipped") or []
    if skipped:
        lines.append(f"- **Repositories skipped:** {len(skipped)} — "
                     + ", ".join(str(s) for s in skipped[:10]))
    lines.append("")

    # ─── Coverage ────────────────────────────────────────────────────
    # Before the findings on purpose: a zero from an ecosystem nobody audited
    # looks exactly like a zero from a clean one.
    sources = summary.get("sources") or {}
    not_checked = summary.get("not_checked") or []
    lines += ["## Coverage & sources", ""]
    if sources:
        lines.append("Findings by auditor: "
                     + ", ".join(f"{k} — {v}" for k, v in sorted(sources.items())))
        lines.append("")
    if not_checked:
        partial = sum(1 for i in not_checked if i.get("status") == "partial")
        rest = len(not_checked) - partial
        headline = f"**Not fully checked ({len(not_checked)}).**"
        if partial and rest:
            headline += (
                f" {partial} saw the direct dependencies but not the "
                "transitive tree; the rest fell back to lock files and "
                "OSV.dev, or were skipped entirely."
            )
        elif partial:
            # No "rest" to describe. Saying there is one invents a second
            # category of gap that this run does not have.
            headline += (" These saw the direct dependencies but not the "
                         "transitive tree.")
        else:
            headline += (" These fell back to lock files and OSV.dev, or were "
                         "skipped entirely.")
        lines += [
            headline + " Treat a zero here as *unknown*, not as *safe*.",
            "",
        ]
        for item in not_checked:
            where = item.get("repo", "?")
            if item.get("subproject"):
                where = f"{where}/{item['subproject']}"
            reason = (item.get("reason") or "").strip().replace("\n", " ")
            lines.append(
                f"- `{where}` — {item.get('ecosystem', '?')} via "
                f"{item.get('tool', '?')}: {reason[:300]}"
            )
        lines.append("")
    else:
        lines += ["Every detected ecosystem was audited by its native tool.", ""]

    # ─── AI report ───────────────────────────────────────────────────
    report = (summary.get("ai_report") or "").strip()
    if report:
        engine = summary.get("ai_report_engine") or "?"
        lines += [
            "## Executive summary",
            "",
            f"_Written by {PRODUCT} using {engine} over the deterministic audit "
            "facts above. The facts are measured; only the analysis is generated._",
            "",
            report,
            "",
        ]
    elif summary.get("ai_report_error"):
        lines += ["## Executive summary", "",
                  f"_Not generated: {summary['ai_report_error']}_", ""]

    # ─── Findings ────────────────────────────────────────────────────
    lines += ["## Findings by repository", ""]
    by_repo: dict[str, list[Any]] = {}
    for f in findings:
        by_repo.setdefault(f.repo_slug, []).append(f)

    clean_budget = MAX_CLEAN_ROWS
    dropped = 0
    for repo in sorted(by_repo):
        rows = sorted(
            by_repo[repo],
            key=lambda r: (_SEV_RANK.get(r.severity, 5), r.outdated == "none", r.package),
        )
        vulnerable = [r for r in rows if r.severity != "none"]
        outdated = [r for r in rows if r.severity == "none" and r.outdated != "none"]
        lines += [
            f"### {repo}",
            "",
            f"{len(rows)} packages · {len(vulnerable)} vulnerable · "
            f"{len(outdated)} outdated",
            "",
        ]
        if vulnerable:
            lines += ["**Vulnerable**", ""]
            for r in vulnerable:
                target = r.latest_version or "?"
                lines.append(
                    f"- **{_SEV_LABEL.get(r.severity, r.severity.upper())}** "
                    f"`{r.package}` {r.current_version} → {target} "
                    f"({r.ecosystem}, {r.outdated})"
                    + (f" — {_vuln_bits(r.vulns)}" if r.vulns else "")
                )
            lines.append("")
        if outdated:
            shown = outdated[:clean_budget] if clean_budget > 0 else []
            dropped += len(outdated) - len(shown)
            clean_budget -= len(shown)
            if shown:
                lines += ["**Outdated (no known vulnerability)**", ""]
                for r in shown:
                    lines.append(
                        f"- `{r.package}` {r.current_version} → "
                        f"{r.latest_version or '?'} ({r.ecosystem}, {r.outdated})"
                    )
                lines.append("")
    if dropped:
        lines += [
            f"_{dropped} further outdated packages with no known vulnerability "
            "were omitted to keep this document readable — they are all listed "
            "in the app._",
            "",
        ]

    # ─── Hygiene ─────────────────────────────────────────────────────
    hygiene = (summary.get("hygiene") or {}).get("items") or []
    if hygiene:
        lines += ["## Supply-chain hygiene", ""]
        for item in hygiene:
            lines.append(
                f"- **{item.get('kind', '?')}** in `{item.get('repo', '?')}`: "
                f"{item.get('detail', '')}"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


__all__ = ["PRODUCT", "build_markdown"]
